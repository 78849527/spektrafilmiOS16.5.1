#!/usr/bin/env python3
"""Use the actual pinned fast_stats.py to derive deterministic Numba RNG cases.

This proves only the one-thread, explicitly seeded source path. Numba's
unseeded parallel prange worker states and scheduling are NOT covered.
Does not import SpektraFilm package __init__ (optional exiv2/RAW bindings).
"""
from __future__ import annotations

import hashlib
import importlib.util
import math
from pathlib import Path

import numba
import numpy as np
from numba import njit

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/spektrafilm/utils/fast_stats.py"
GRAIN = ROOT / "src/spektrafilm/model/grain.py"
DEST = ROOT / "ios/SpektraFilmPort/GeneratedSourceNumbaSingleThreadReference.swift"
FAST_BLOB = "9e80d29ce6b9f7820ae70f5c09da15edfaa70a0d"
GRAIN_BLOB = "f2d2b23e3eab4f4a1d919f69bcb4aceb714e024d"


def git_blob(path: Path) -> str:
    raw = path.read_bytes()
    return hashlib.sha1(
        b"blob " + str(len(raw)).encode("ascii") + b"\\0" + raw
    ).hexdigest()


@njit
def seed_numba(seed: int) -> None:
    # The source's np.random.randn is compiled under Numba and must be
    # explicitly seeded INSIDE Numba, not by Python np.random.seed.
    np.random.seed(seed)


def swift(values):
    return "[" + ", ".join(format(float(x), ".17g") for x in values) + "]"


def main():
    assert git_blob(SOURCE) == FAST_BLOB, "fast_stats.py changed: review before rebaseline"
    assert git_blob(GRAIN) == GRAIN_BLOB, "grain.py changed: review before rebaseline"
    assert "fast_lognormal_from_mean_std" in GRAIN.read_text(encoding="utf8")
    spec = importlib.util.spec_from_file_location(
        "source_pinned_fast_stats_numba", SOURCE
    )
    assert spec is not None and spec.loader is not None
    source = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(source)

    numba.set_num_threads(1)
    count = 64
    # Compile first; reset the source Numba RNG after JIT warm-up.
    source.fast_lognormal_from_mean_std(
        np.ones(2, dtype=np.float64),
        np.ones(2, dtype=np.float64) * 0.25,
    )
    seeds = (0, 8888, 123456)
    lines = [
        "// Generated by executing the unmodified pinned upstream fast_stats.py.",
        "// Single-thread explicitly seeded Numba RNG ONLY; not prange parity.",
        "enum GeneratedSourceNumbaSingleThreadReference {",
        '    static let fastStatsBlob = "' + FAST_BLOB + '"',
        '    static let grainBlob = "' + GRAIN_BLOB + '"',
        "    struct Case {",
        "        let seed: UInt32",
        "        let std: [Double]",
        "        let normal: [Double]",
        "        let lognormal: [Double]",
        "    }",
        "    static let cases: [Case] = [",
    ]
    for seed in seeds:
        # All standard deviations are > source microstructure threshold
        # 0.05 and > fast_lognormal's 1e-6 no-random threshold.
        std = np.asarray(
            [0.08 + 0.013 * (i % 17) for i in range(count)],
            dtype=np.float64,
        )
        mean = np.ones(count, dtype=np.float64)
        numpy_legacy_normals = np.random.RandomState(seed).standard_normal(count)
        seed_numba(seed)
        original_numba = source.fast_lognormal_from_mean_std(mean, std)
        sigma2 = np.log(1.0 + (std * std) / (mean * mean))
        mu = np.log(mean) - sigma2 / 2.0
        reconstructed = np.exp(mu + np.sqrt(sigma2) * numpy_legacy_normals)
        err = float(np.max(np.abs(original_numba - reconstructed)))
        assert np.isfinite(original_numba).all() and err < 1e-12, (
            "Source Numba RNG differed from seeded single-thread NumPy: "
            f"seed={seed} error={err}"
        )
        lines.extend([
            "        Case(",
            f"            seed: {seed},",
            f"            std: {swift(std)},",
            f"            normal: {swift(numpy_legacy_normals)},",
            f"            lognormal: {swift(original_numba)}",
            "        ),",
        ])
        print(
            f"PASS: pinned unmodified Numba fast_lognormal_from_mean_std "
            f"seed={seed}, n={count}, 1 thread, max abs={err:.3g}"
        )
    lines.extend(["    ]", "}"])
    DEST.write_text("\\n".join(lines) + "\\n", encoding="utf8")
    print("NOT CERTIFIED: Numba parallel prange threads, on-device GPU, full RGB image")


if __name__ == "__main__":
    main()
