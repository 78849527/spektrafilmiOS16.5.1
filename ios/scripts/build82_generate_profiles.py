#!/usr/bin/env python3
"""Build82: generate stock-exact Hanatos parameters from original profiles.

Source profile measurements are used directly, including 81x3
10**log_sensitivity, original erf4 + poly4 correction parameters and
per-stock source illuminant white. Never invent or zero a missing surface.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import colour
import numpy as np

ROOT=Path(__file__).resolve().parents[2]
PROFILES=ROOT/"src/spektrafilm/data/profiles"
SOURCE_NPY=ROOT/"src/spektrafilm/data/luts/spectral_upsampling/irradiance_xy_tc.npy"
SOURCE_BLOB="7b81b9d23f8f4c599c6b2ae3d949e9a2d6f3c38a"
SHAPE=colour.SpectralShape(380,780,5)


def load_illuminant(name:str)->np.ndarray:
    table=colour.SDS_LIGHT_SOURCES if name=="T" else colour.SDS_ILLUMINANTS
    light="Incandescent" if name=="T" else name
    a=np.asarray(table[light].copy().align(SHAPE).values,dtype=np.float64)
    return a/np.mean(a)


def source_white(illuminant:np.ndarray)->list[float]:
    cie=np.asarray(colour.MSDS_CMFS[
        "CIE 1931 2 Degree Standard Observer"].copy().align(SHAPE).values,
        dtype=np.float64)
    xyz=np.einsum("w,wc->c",illuminant,cie)
    return list(map(float,xyz[:2]/xyz.sum()))


def swift_float(a:float)->str:
    x=float(a)
    if not np.isfinite(x):
        raise ValueError("Generated Swift spectral data cannot contain NaN/inf")
    return format(x,".17g")


def swift_vector(a)->str:
    return "["+",".join(swift_float(x) for x in np.asarray(a).ravel())+"]"


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--output",type=Path,required=True)
    args=p.parse_args()
    if colour.__version__!="0.4.6":
        raise RuntimeError("Original colour-science version 0.4.6 required")
    spectral=np.load(SOURCE_NPY,allow_pickle=False)
    if spectral.shape!=(192,192,81) or spectral.dtype!=np.dtype("<f2"):
        raise RuntimeError(f"Source irradiance NPY shape/dtype drift: {spectral.shape} {spectral.dtype}")
    lines=[
        "import Foundation","",
        "/// AUTOGENERATED from original source film profiles; do not edit.","enum Build82GeneratedHanatosProfiles {",
        f'    static let sourceBlob = "{SOURCE_BLOB}"',
        f'    static let sourceSHA256 = "{hashlib.sha256(SOURCE_NPY.read_bytes()).hexdigest()}"',
        "    static let all: [String: Build82OriginalSpectralRuntime.Profile] = ["
    ]
    count=0
    for path in sorted(PROFILES.glob("*.json")):
        doc=json.loads(path.read_bytes())
        info,raw=doc["info"],doc["data"]
        if info["stage"]!="filming" or info["support"]!="film":
            continue
        stock=info["stock"]
        sens=np.nan_to_num(10.0**np.asarray(raw["log_sensitivity"],
                                          dtype=np.float64))
        window=np.asarray(raw["hanatos2025_adaptation_window_params"],
                          dtype=np.float64)
        surface=np.asarray(raw["hanatos2025_adaptation_surface_params"],
                           dtype=np.float64)
        if sens.shape!=(81,3) or window.shape!=(4,) or surface.shape!=(3,15):
            raise RuntimeError(
                f"Source profile adaptation shape not supported: "
                f"{stock} {sens.shape} {window.shape} {surface.shape}")
        ill=load_illuminant(info["reference_illuminant"])
        white=source_white(ill)
        if ill.shape!=(81,):
            raise RuntimeError(f"Invalid reference illuminant: {stock}")
        digest=hashlib.sha256(path.read_bytes()).hexdigest()
        lines+= [
            f'        "{stock}": .init(',
            f'            stock: "{stock}",',
            f'            reference: "{info["reference_illuminant"]}",',
            f'            referenceXY: .init(x:{swift_float(white[0])},y:{swift_float(white[1])}),',
            f'            illuminant:{swift_vector(ill)},',
            f'            sensitivity:{swift_vector(sens)},',
            f'            window:{swift_vector(window)},',
            f'            surface:[{",".join(swift_vector(s) for s in surface)}]',
            "        ),",
        ]
        count+=1
        print(f"Build82 profile {stock}, original profile SHA256={digest}")
    if count!=20:
        raise RuntimeError(f"20 original film profiles expected, got {count}")
    lines+=["    ]","}",""]
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text("\n".join(lines),encoding="utf8")
    print(f"PASS Build82 source 20 film adaptation profiles, "
          f"source F16 irradiation sha256={hashlib.sha256(SOURCE_NPY.read_bytes()).hexdigest()}")


if __name__=="__main__":
    main()
