#!/usr/bin/env python3
"""Generate Float64 scanner-glare fixtures by EXECUTING pinned source glare.py.

The actual upstream glare.py imports original fast_stats.py and
fast_gaussian_filter.py. Load them without importing the SpektraFilm
package __init__ (optional RAW/exiv2), and fail when source blobs drift.
NUMBA_NUM_THREADS=1 and NUMBA_THREADING_LAYER=workqueue pin a controlled
diagnostic, not the default unseeded multiworker production field.
"""
from __future__ import annotations
import hashlib
import importlib.util
import os
import sys
import types
from pathlib import Path

import numba
import numpy as np
from numba import njit, prange

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src/spektrafilm"
OUT = ROOT / "ios/SpektraFilmPort/GeneratedSourceScannerGlareReference.swift"
BLOBS = {
    "model/glare.py": "e8610f13430d45be749ae31a5284eef2c2b7a362",
    "utils/fast_stats.py": "9e80d29ce6b9f7820ae70f5c09da15edfaa70a0d",
    "utils/fast_gaussian_filter.py": "8918c673ea0fb3f5d9ae820ca85bf6db4aba457a",
}


def git_blob(file: Path) -> str:
    data = file.read_bytes()
    return hashlib.sha1(
        b"blob " + str(len(data)).encode("ascii") + b"\0" + data
    ).hexdigest()


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


@njit(parallel=True)
def seed_one_worker(seed):
    for _ in prange(1):
        np.random.seed(seed)


@njit(parallel=True)
def generate_normals(count):
    output = np.empty(count, dtype=np.float64)
    for i in prange(count):
        output[i] = np.random.randn()
    return output


def swift_float(seq):
    return "[" + ", ".join(format(float(x), ".17g") for x in seq) + "]"


def main():
    assert os.environ.get("NUMBA_NUM_THREADS") == "1", (
        "Controlled source stream requires NUMBA_NUM_THREADS=1"
    )
    assert os.environ.get("NUMBA_THREADING_LAYER") == "workqueue", (
        "Controlled source stream requires workqueue"
    )
    for p, blob in BLOBS.items():
        assert git_blob(SRC / p) == blob, (
            f"Pinned original {p} changed; require source re-audit"
        )

    numba.set_num_threads(1)
    assert numba.get_num_threads() == 1
    for pkg in ("spektrafilm", "spektrafilm.utils", "spektrafilm.model"):
        mod = types.ModuleType(pkg)
        mod.__path__ = [str(SRC)]
        sys.modules[pkg] = mod
    load("spektrafilm.utils.fast_stats", SRC / "utils/fast_stats.py")
    load("spektrafilm.utils.fast_gaussian_filter",
         SRC / "utils/fast_gaussian_filter.py")
    original = load("spektrafilm.model.glare", SRC / "model/glare.py")

    # Compile before seeding, otherwise jit warm-up changes the PRNG.
    original.compute_random_glare_amount(0.03, 0.7, 0.5, (2, 2))
    generate_normals(2)

    cases = [
        # seed, height, width, percent, roughness, sigma, enabled
        (0, 5, 7, 0.03, 0.7, 0.5, True),
        (8888, 6, 4, 0.12, 1.4, 3.4, True),
        (123456, 4, 8, 0.07, 0.35, 0.0, True),
        (8888, 4, 5, 0.03, 0.0, 0.5, True),
        (0, 3, 4, 0.03, 0.7, 0.5, False),
        (123456, 3, 6, 0.0, 0.7, 0.5, True),
    ]
    lines = [
        "// Generated by EXECUTING original pinned glare.py + fast_stats.py",
        "// + fast_gaussian_filter.py with one explicitly seeded prange worker.",
        "// NOT evidence of unseeded Numba parallel production RNG parity.",
        "enum GeneratedSourceScannerGlareReference {",
        '    static let glareBlob = "' + BLOBS["model/glare.py"] + '"',
        '    static let statsBlob = "' + BLOBS["utils/fast_stats.py"] + '"',
        '    static let filterBlob = "' + BLOBS["utils/fast_gaussian_filter.py"] + '"',
        "    struct Case {",
        "        let seed: UInt32",
        "        let width: Int",
        "        let height: Int",
        "        let percent: Double",
        "        let roughness: Double",
        "        let blur: Double",
        "        let enabled: Bool",
        "        let sourceNormals: [Double]",
        "        let amounts: [Double]",
        "        let inputXYZ: [Double]",
        "        let illuminantXYZ: [Double]",
        "        let outputXYZ: [Double]",
        "    }",
        "    static let cases: [Case] = [",
    ]
    for seed, height, width, percent, roughness, blur, enabled in cases:
        count = height * width
        xyz = np.asarray([
            [[0.12 + ((p * 3 + c) % 31) * 0.017 for c in range(3)]
             for p in range(y * width, (y + 1) * width)]
            for y in range(height)
        ], dtype=np.float64)
        white = np.asarray([0.95047, 1.0, 1.08883], dtype=np.float64)
        obj = types.SimpleNamespace(
            active=enabled, percent=percent, roughness=roughness, blur=blur
        )
        seed_one_worker(seed)
        expected_xyz = original.add_glare(xyz.copy(), white, obj)
        seed_one_worker(seed)
        if enabled and percent > 0:
            amount = original.compute_random_glare_amount(
                percent, roughness, blur, (height, width)
            )
        else:
            amount = np.zeros((height, width), dtype=np.float64)

        seed_one_worker(seed)
        normals = generate_normals(count)
        assert expected_xyz.shape == (height, width, 3)
        assert np.isfinite(expected_xyz).all()
        if enabled and percent > 0:
            manual = xyz + amount[:, :, None] * white[None, None, :]
            assert np.max(np.abs(manual - expected_xyz)) < 1e-12
        else:
            assert np.array_equal(xyz, expected_xyz)
        lines.extend([
            "        Case(",
            f"            seed: {seed}, width: {width}, height: {height},",
            f"            percent: {percent:.17g}, roughness: {roughness:.17g},",
            f"            blur: {blur:.17g}, enabled: {'true' if enabled else 'false'},",
            f"            sourceNormals: {swift_float(normals)},",
            f"            amounts: {swift_float(amount.ravel())},",
            f"            inputXYZ: {swift_float(xyz.ravel())},",
            f"            illuminantXYZ: {swift_float(white)},",
            f"            outputXYZ: {swift_float(expected_xyz.ravel())}",
            "        ),"
        ])
        print(
            f"PASS: actual source glare.py seed={seed} {width}x{height}, "
            f"blur={blur}, enabled={enabled}, "
            f"XYZ channels={expected_xyz.size}"
        )
    lines.extend(["    ]", "}"])
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("NOT CERTIFIED: unseeded Numba prange workers, source XYZ production integration, full RGB or iPhone.")


if __name__ == "__main__":
    main()
