#!/usr/bin/env python3
"""Independent ORIGINAL Python fast_interp H-D boundary/interval references.

Runs the upstream SpektraFilm production interpolator, not a Swift imitation.
Uses all 20 camera film Float64 JSON exposure axes and density curves,
including four reversal stocks and pre-DIR corrected H-D curves.
Reference is a stage-limited test; it does not certify full random grain/RAW.
"""
from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "ios/scripts"))

from generate_dir import matrix
from generate_source_film_dir_print_chain import upstream_film

PROFILES = ROOT / "src/spektrafilm/data/profiles"
OUT = ROOT / "ios/SpektraFilmPort/GeneratedSourceHDInterpolationReference.swift"


def swift_string(value: str) -> str:
    return json.dumps(value)


def f64_base64(values: np.ndarray) -> str:
    values = np.asarray(values, dtype="<f8")
    if not np.isfinite(values).all():
        raise ValueError("Nonfinite original H-D reference")
    return base64.b64encode(np.ascontiguousarray(values).tobytes()).decode("ascii")


def probes(axis: np.ndarray) -> np.ndarray:
    if axis.shape != (256,) or np.any(np.diff(axis) < 0):
        raise ValueError("Invalid original 256-node monotone exposure axis")
    indices = (0, 1, 2, 3, 17, 64, 127, 128, 192, 253, 254, 255)
    mid = (0, 1, 17, 64, 127, 192, 254)
    samples = [
        float(axis[0] - 0.37),
        float(np.nextafter(axis[0], -np.inf)),
        *[float(axis[i]) for i in indices],
        *[float((axis[i] + axis[i+1]) / 2) for i in mid],
        float(np.nextafter(axis[-1], np.inf)),
        float(axis[-1] + 0.37),
    ]
    # Broad random-free, deterministic non-node samples across the whole
    # original source domain. Preserve actual binary64 inputs as generated.
    samples.extend(np.linspace(axis[0], axis[-1], 11, dtype=np.float64).tolist())
    return np.asarray(samples, dtype=np.float64)


def main() -> None:
    # Reuse the established source-only module loader. It executes the real
    # upstream density_curves.py, couplers.py and fast_interp.py rather than
    # importing the package's eager RAW/exiv2 initialization dependency.
    # No source calculation, parameter or interpolation algorithm is replaced.
    density_source, couplers_source, _ = upstream_film()
    lines = [
        "// GENERATED by running upstream Python fast_interp on actual Float64 JSON.",
        "// All 20 filming stocks; exact endpoints, nodes, half-intervals, out of range.",
        "// Scope: film H-D interpolation only, not end-to-end image certification.",
        "import Foundation",
        "enum GeneratedSourceHDInterpolationReference {",
        "    struct Record {",
        "        let stock: String",
        "        let exposures: String",
        "        let original: String",
        "        let correctedBeforeDIR: String",
        "    }",
        "    static let records: [Record] = [",
    ]
    total = 0
    films = 0
    reversals = 0
    for file in sorted(PROFILES.glob("*.json")):
        doc = json.loads(file.read_text(encoding="utf-8"))
        info, data = doc["info"], doc["data"]
        if info["stage"] != "filming":
            continue
        films += 1
        positive = info["type"] == "positive"
        reversals += int(positive)
        axis = np.asarray(data["log_exposure"], dtype=np.float64)
        curves = np.asarray(data["density_curves"], dtype=np.float64)
        curves = curves - np.nanmin(curves, axis=0)
        pre_dir = couplers_source.compute_density_curves_before_dir_couplers(
            curves, axis, matrix(info["stock"], positive), positive=positive
        )
        x = probes(axis)
        inputs = np.repeat(x.reshape(-1, 1, 1), 3, axis=2)
        original = density_source.interpolate_exposure_to_density(inputs, curves, axis, 1.0)
        corrected = density_source.interpolate_exposure_to_density(inputs, pre_dir, axis, 1.0)
        if original.shape != (len(x), 1, 3) or corrected.shape != original.shape:
            raise ValueError("Unexpected source H-D reference shape")
        total += original.size * 2
        lines.extend([
            "        Record(",
            "            stock: " + swift_string(info["stock"]) + ",",
            "            exposures: " + swift_string(f64_base64(x)) + ",",
            "            original: " + swift_string(f64_base64(original)) + ",",
            "            correctedBeforeDIR: " + swift_string(f64_base64(corrected)),
            "        ),",
        ])
    if films != 20 or reversals != 4:
        raise AssertionError(f"Expected 20 films, 4 reversals; got {films}, {reversals}")
    lines.extend(["    ]", "}"])
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"PASS: upstream Python fast_interp generated {total} Float64 outputs "
        f"across {films} films ({reversals} reversal stocks) for normal and "
        "pre-DIR-corrected source H-D. No mobile LUT used."
    )


if __name__ == "__main__":
    main()
