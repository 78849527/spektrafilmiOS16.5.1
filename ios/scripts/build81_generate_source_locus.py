#!/usr/bin/env python3
"""Generate exact original CIE 1931 spectral locus from pinned SpektraFilm.

The upstream spectral_locus_xy() reads colour-science's measured 1931 2°
CMFs at 380–700nm every 5nm, 65 vertices plus closure. No hard-coded
hand-drawn polygon is allowed for the original default gamut compressor.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import subprocess
from pathlib import Path

import colour
import numpy as np

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/"src/spektrafilm/utils/gamut_compression.py"
BLOB="9783e7fcfc2909c4acdf2da53595c5404645dde9"


def source_locus():
    got=subprocess.check_output(
        ["git","hash-object",str(SOURCE)],cwd=ROOT,text=True
    ).strip()
    if got!=BLOB:
        raise RuntimeError(f"Upstream input gamut source drift: {got}")
    if colour.__version__!="0.4.6":
        raise RuntimeError("Original colour-science==0.4.6 required")
    tree=ast.parse(SOURCE.read_text("utf8"),filename=str(SOURCE))
    nodes=[x for x in tree.body
           if isinstance(x,ast.FunctionDef) and x.name=="spectral_locus_xy"]
    if len(nodes)!=1:
        raise RuntimeError("Missing one original spectral_locus_xy function")
    namespace={
        "np":np,"colour":colour,"_SPECTRAL_LOCUS_XY_CACHE":None,
        "__name__":"__build81_oracle__"
    }
    module=ast.fix_missing_locations(ast.Module(body=nodes,type_ignores=[]))
    exec(compile(module,str(SOURCE),"exec"),namespace)
    locus=namespace["spectral_locus_xy"]()
    if locus.shape!=(66,2) or locus.dtype!=np.dtype("float64"):
        raise RuntimeError(f"Unexpected CIE spectral locus: {locus.shape} {locus.dtype}")
    if not np.all(np.isfinite(locus)) or not np.array_equal(locus[0],locus[-1]):
        raise RuntimeError("Invalid or nonclosed original CIE spectral polygon")
    return locus


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--output",type=Path,required=True)
    args=p.parse_args()
    locus=source_locus()
    checksum=hashlib.sha256(
        np.ascontiguousarray(locus,dtype="<f8").tobytes()
    ).hexdigest()
    rows=[
        "import Foundation",
        "",
        "/// GENERATED by build81_generate_source_locus.py from exact Python AST.",
        "/// CIE 1931 2-degree, 380..700nm/5nm, 65 vertices + closure.",
        "/// Required for the source-default XY gamut compression.",
        "enum Build81GeneratedSpectralLocus {",
        f'    static let sourceBlob = "{BLOB}"',
        f'    static let float64SHA256 = "{checksum}"',
        "    static let points: [Build81OriginalInputGamut.Point] = [",
    ]
    for x,y in locus:
        rows.append(f"        .init(x:{float(x):.17g},y:{float(y):.17g}),")
    rows+=["    ]","}",""]
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text("\n".join(rows),encoding="utf8")
    print(f"PASS Build81 true original CIE 1931 locus 66 xy points, "
          f"Float64 SHA256={checksum}")


if __name__=="__main__":
    main()
