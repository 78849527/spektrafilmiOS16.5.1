import Foundation

/// Build77/03 original Python digest ↔ actual source-optical CC resolver.
/// Verifies default database-on and explicit database-off in the REAL
/// OriginalPrintOptics.sourceNeutralCC used by SpectralPhysics.
/// This does not certify the output spectrum or final RGB.
@main
struct Build77NeutralFilterParity {
    enum Failure: LocalizedError {
        case invalid(String)
        var errorDescription:String? {
            if case .invalid(let message) = self { return message }
            return nil
        }
    }

    static func sourceNumber(_ object:[String:Any], _ key:String) throws -> Double {
        guard let value=object[key] as? NSNumber,
              value.doubleValue.isFinite else {
            throw Failure.invalid("Missing original Python number: "+key)
        }
        return value.doubleValue
    }

    static func main() throws {
        guard CommandLine.arguments.count==2 else {
            throw Failure.invalid("Expected independent original Python digest JSON")
        }
        let raw=try Data(contentsOf: URL(fileURLWithPath:CommandLine.arguments[1]))
        let reference=try Build77ExactJSONValue.decodeObject(from:raw)
        guard let sourceSHA=reference["upstream_sha"] as? String,
              sourceSHA=="3bb2c2d2801ff68b92019cf1dbcbb133d60832bc",
              let cases=reference["cases"] as? [[String:Any]],
              cases.count==360,
              let db=reference["neutral_database"] as? [String:Any]
        else { throw Failure.invalid("Original Python digest data invalid") }

        // Source JSON lookup: stock → selected paper + original TH-KG3.
        // The actual production dictionary is separately generated by
        // generate_original_optics.py and also checked below.
        var neutral:[String:[Double]] = [:]
        for (paper,illuminants) in db {
            guard let nested=illuminants as? [String:Any] else {
                throw Failure.invalid("Malformed source database paper "+paper)
            }
            if let byFilm=nested["TH-KG3"] as? [String:Any] {
                for (film,rawTriplet) in byFilm {
                    guard let values=rawTriplet as? [NSNumber],
                          values.count==3 else {
                        throw Failure.invalid("Malformed source CC triplet")
                    }
                    neutral[film+"|"+paper]=values.map(\.doubleValue)
                }
            }
        }
        var baseCount=0, offCount=0
        var sourceFilms=Set<String>(),papers=Set<String>()
        for item in cases {
            guard let mode=item["mode"] as? String,
                  mode=="base" || mode=="neutral_database_off"
            else { continue }
            guard let filmInfo=item["film_info"] as? [String:Any],
                  let paperInfo=item["paper_info"] as? [String:Any],
                  let film=filmInfo["stock"] as? String,
                  let paper=paperInfo["stock"] as? String,
                  let expected=item["expected"] as? [String:Any],
                  let enlarger=expected["enlarger"] as? [String:Any] else {
                throw Failure.invalid("Original Python neutral case absent")
            }
            var settings=OriginalPrintOptics.Settings()
            settings.enabled=true
            settings.illuminant = .thKG3
            settings.neutralPrintFiltersFromDatabase = mode=="base"
            let candidate=try OriginalPrintOptics.sourceNeutralCC(
                filmID:film,paperID:paper,settings:settings,
                neutralByPair:GeneratedOriginalOptics.neutralCMYByPair
            )
            let independent=try OriginalPrintOptics.sourceNeutralCC(
                filmID:film,paperID:paper,settings:settings,
                neutralByPair:neutral
            )
            let fromPython=try [
                sourceNumber(enlarger,"c_filter_neutral"),
                sourceNumber(enlarger,"m_filter_neutral"),
                sourceNumber(enlarger,"y_filter_neutral"),
            ]
            for c in 0..<3 {
                guard candidate[c].bitPattern==fromPython[c].bitPattern,
                      independent[c].bitPattern==fromPython[c].bitPattern else {
                    throw Failure.invalid(
                        "Generated ACTUAL iOS filter and Python digest "
                        + "differ on "+film+"|"+paper+"|"+mode
                        + " channel \(c)"
                    )
                }
            }
            if mode=="base" {
                baseCount+=1
                sourceFilms.insert(film);papers.insert(paper)
            } else {
                offCount+=1
            }
        }
        guard baseCount==160,offCount==20,
              sourceFilms.count==20,papers.count==8 else {
            throw Failure.invalid("Expected 160 on and 20 off source cases")
        }
        var disabled=OriginalPrintOptics.Settings()
        disabled.enabled=true
        disabled.illuminant = .thKG3L
        disabled.neutralPrintFiltersFromDatabase=true
        let lens=try OriginalPrintOptics.sourceNeutralCC(
            filmID:"kodak_portra_400",paperID:"kodak_portra_endura",
            settings:disabled,
            neutralByPair:GeneratedOriginalOptics.neutralCMYByPair
        )
        guard lens==[0.0,65.0,55.0] else {
            throw Failure.invalid("TH-KG3-L must keep original schema defaults")
        }
        // Python leaves the source defaults when a row is absent. It never
        // reuses a neighboring stock's neutral filters.
        let missing=try OriginalPrintOptics.sourceNeutralCC(
            filmID:"not-a-real-film",paperID:"not-a-real-paper",
            settings:disabled,
            neutralByPair:neutral
        )
        guard missing==[0.0,65.0,55.0] else {
            throw Failure.invalid("Missing source row must preserve defaults")
        }
        disabled.illuminant = .thKG3
        var rejected=false
        do {
            _ = try OriginalPrintOptics.sourceNeutralCC(
                filmID:"corrupt",paperID:"corrupt",
                settings:disabled,
                neutralByPair:["corrupt|corrupt":[1.0,2.0]]
            )
        } catch { rejected=true }
        guard rejected else {
            throw Failure.invalid("Corrupt optical database row must fail")
        }
        print("PASS original Python RuntimePhotoParams → actual Swift "
              + "optical neutral source: 160 stock/paper database-on, "
              + "20 explicit database-off, all 3 CMY Float64 bitwise; "
              + "TH-KG3-L defaults, missing and corrupted rows checked. "
              + "Scope: database selection, NOT resulting RGB.")
    }
}
